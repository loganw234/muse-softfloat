/* hwdiff.c - audit differential: muse-softfloat vs x86-64 hardware.
 * Scratch-only audit code. Build:
 *   gcc -std=c11 -O2 -ffp-contract=off -I<repo>/include hwdiff.c <repo src> -lm
 */
#define _GNU_SOURCE
#include "hwcore.h"

enum { OP_ADD, OP_SUB, OP_MUL, OP_DIV, OP_SQRT, OP_CONV };
typedef uint64_t (*bfn)(uint64_t, uint64_t, int, msf_flags_t *);
typedef uint64_t (*ufn)(uint64_t, int, msf_flags_t *);
typedef uint64_t (*ffn)(uint64_t, uint64_t, uint64_t, int, msf_flags_t *);
typedef uint64_t (*tfn)(uint64_t, msf_flags_t *);
typedef struct { const char *n; int op, d, a, b; bfn f; } BinEnt;
typedef struct { const char *n; int op, d, a; ufn f; } UnEnt;
typedef struct { const char *n; int d, a, b, c; ffn f; } FmaEnt;
typedef struct { const char *n; int d, sgn, bits; ufn f; } FromEnt;
typedef struct { const char *n; int s, sgn, bits, exact, mode; tfn f; } ToEnt;
typedef struct { const char *n; int d, exact, mode; ufn f; } RtiEnt;
#include "wrappers.h"  /* generated by genwrap.py into the build dir */
#include "wrappers2.h"

static long g_mism = 0, g_checked = 0, g_skipped = 0;
static int g_print_limit = 6;
static void report(const char *name, int m, const char *in, uint64_t got, uint32_t gfl, uint64_t exp, uint32_t efl, int *printed) {
    g_mism++;
    if (*printed < g_print_limit) {
        printf("  MISMATCH %s %s %s -> got %llx fl=%02x expected %llx fl=%02x\n", name, MN[m], in,
               (unsigned long long)got, gfl, (unsigned long long)exp, efl);
        (*printed)++;
    }
}

static double dop(int op, double x, double y) {
    switch (op) { case OP_ADD: return hadd(x, y); case OP_SUB: return hsub(x, y); case OP_MUL: return hmul(x, y);
    case OP_DIV: return hdiv(x, y); default: return hsqrt(x); }
}
/* exact-tie detector for binary64 destinations under ties-to-away: 1 tie, 0 none, -1 unknown */
static int tie64(int op, double x, double y, double r) {
    if (isnan(r)) return 0;
    if (op == OP_SQRT) return 0;
    if (op == OP_ADD || op == OP_SUB) {
        if (op == OP_SUB) y = -y;
        if (isinf(x) || isinf(y)) return 0;
        hw_begin(0); double s = hadd(x, y), bb = hsub(s, x); double e = hadd(hsub(x, hsub(s, bb)), hsub(y, bb)); hw_end();
        if (isinf(s) || e == 0) return 0;
        double n = nextafter(s, e > 0 ? INFINITY : -INFINITY);
        return 2 * fabs(e) == fabs(n - s);
    }
    if (op == OP_MUL) {
        if (x == 0 || y == 0 || isinf(x) || isinf(y)) return 0;
        hw_begin(0); double p = hmul(x, y); double e = hfma(x, y, -p); hw_end();
        if (isinf(p)) return 0;
        if (fabs(p) < 0x1p-960) return -1;
        if (e == 0) return 0;
        double n = nextafter(p, e > 0 ? INFINITY : -INFINITY);
        return 2 * fabs(e) == fabs(n - p);
    }
    if (op == OP_DIV) {
        if (x == 0 || y == 0 || isinf(x) || isinf(y) || isinf(r)) return 0;
        if (fabs(r) >= 0x1p-1021) return 0;
        return -1;
    }
    return -1;
}

static Res ref_arith(int op, int d, int A, int B, uint64_t a, uint64_t b, int m) {
    Res R = {0, 0, 0};
    const Fmt *fd = FMT(d);
    double x = b2d(A, a), y = (op == OP_SQRT || op == OP_CONV) ? 0 : b2d(B, b);
    if (op == OP_CONV) {
        if (d == 64) { R.r = d2u(x); return R; }
        R.r = round_from_double(x, d, m, &R.fl); return R;
    }
    if (d == 64) {
        if (m < 4) { hw_begin(m); double r = dop(op, x, y); R.fl = hw_end(); R.r = isnan(r) ? b_defnan(fd) : d2u(r); return R; }
        hw_begin(0); double r = dop(op, x, y); uint32_t fl = hw_end();
        if (isnan(r)) { R.r = b_defnan(fd); R.fl = fl; return R; }
        int t = tie64(op, x, y, r);
        if (t < 0) { R.skip = 1; return R; }
        if (t == 0) { R.r = d2u(r); R.fl = fl; return R; }
        hw_begin(signbit(r) ? 3 : 2); double r2 = dop(op, x, y); R.fl = hw_end(); R.r = d2u(r2); return R;
    }
    hw_begin(1); double r = dop(op, x, y); uint32_t f1 = hw_end();
    if (r == 0 && !(f1 & MSF_FLAG_INEXACT)) { hw_begin(m == 4 ? 0 : m); r = dop(op, x, y); f1 = hw_end(); }
    if (isnan(r)) { R.r = b_defnan(fd); R.fl = f1 & MSF_FLAG_INVALID; return R; }
    uint32_t f2; R.r = round_from_double(odd(r, f1), d, m, &f2);
    R.fl = (f1 & (MSF_FLAG_INVALID | MSF_FLAG_DIVISION_BY_ZERO)) | f2;
    return R;
}
static Res ref_fma(int d, int A, int B, int C, uint64_t a, uint64_t b, uint64_t c, int m) {
    Res R = {0, 0, 0};
    const Fmt *fd = FMT(d);
    double x = b2d(A, a), y = b2d(B, b), z = b2d(C, c);
    if (d == 64) {
        if (m == 4) { R.skip = 1; return R; }
        hw_begin(m); double r = hfma(x, y, z); R.fl = hw_end(); R.r = isnan(r) ? b_defnan(fd) : d2u(r); return R;
    }
    hw_begin(1); double r = hfma(x, y, z); uint32_t f1 = hw_end();
    if (r == 0 && !(f1 & MSF_FLAG_INEXACT)) { hw_begin(m == 4 ? 0 : m); r = hfma(x, y, z); f1 = hw_end(); }
    if (isnan(r)) { R.r = b_defnan(fd); R.fl = f1 & MSF_FLAG_INVALID; return R; }
    uint32_t f2; R.r = round_from_double(odd(r, f1), d, m, &f2);
    R.fl = (f1 & (MSF_FLAG_INVALID | MSF_FLAG_DIVISION_BY_ZERO)) | f2;
    return R;
}

/* ---- NaN-operand rule bookkeeping (SF-0 2.5 matrix, two readings) ---- */
static long nan_cases = 0, nan_flag_bad = 0, nan_h1 = 0, nan_h2 = 0, nan_other = 0, nan_notnan = 0;
static void nan_check(const char *name, int d, int n, const int *w, const uint64_t *v, uint64_t got, uint32_t gfl, int fma_zero_inf) {
    const Fmt *fd = FMT(d);
    int any_s = 0, first = -1, first_s = -1;
    for (int i = 0; i < n; i++) {
        const Fmt *f = FMT(w[i]);
        if (b_isnan(f, v[i])) { if (first < 0) first = i; if (b_issnan(f, v[i])) { any_s = 1; if (first_s < 0) first_s = i; } }
    }
    nan_cases++;
    uint32_t efl = (any_s || fma_zero_inf) ? MSF_FLAG_INVALID : 0;
    if (gfl != efl) { nan_flag_bad++; if (nan_flag_bad <= 5) printf("  NAN-FLAG %s got fl=%02x expected %02x (got %llx)\n", name, gfl, efl, (unsigned long long)got); }
    if (!b_isnan(fd, got)) { nan_notnan++; if (nan_notnan <= 5) printf("  NAN-NOTNAN %s got %llx\n", name, (unsigned long long)got); return; }
    int pick1 = fma_zero_inf ? 2 : first;
    int pick2 = fma_zero_inf ? 2 : (first_s >= 0 ? first_s : first);
    uint64_t e1 = b_nanconv(FMT(w[pick1]), fd, v[pick1]), e2 = b_nanconv(FMT(w[pick2]), fd, v[pick2]);
    if (got == e1) nan_h1++;
    if (got == e2) nan_h2++;
    if (got != e1 && got != e2) { nan_other++; if (nan_other <= 8) { printf("  NAN-PAYLOAD %s got %llx; first-NaN %llx; sNaN-first %llx; ops:", name, (unsigned long long)got, (unsigned long long)e1, (unsigned long long)e2); for (int i = 0; i < n; i++) printf(" %llx", (unsigned long long)v[i]); printf("\n"); } }
}

static uint64_t gen_nanish(const Fmt *f) { /* bias toward NaNs for the NaN pass */
    if (rnd() % 3 == 0) { uint64_t m = rnd() & f->mmask; if (!m) m = 1; return ((rnd() & 1) ? f->sign : 0) | f->emask | m; }
    return gen_val(f);
}

static void test_bins(long n_homog, long n_mixed) {
    for (size_t i = 0; i < sizeof BINS / sizeof BINS[0]; i++) {
        const BinEnt *e = &BINS[i];
        long n = (e->d == e->a && e->a == e->b) ? n_homog : n_mixed;
        const Fmt *fa = FMT(e->a), *fb = FMT(e->b);
        int printed = 0; long mism0 = g_mism;
        for (long k = 0; k < n; k++) {
            uint64_t a = gen_val(fa), b;
            if (e->a == e->b) b = gen_rel(fb, a); else b = gen_val(fb);
            if (rnd() % 16 == 0) { a = gen_nanish(fa); b = gen_nanish(fb); }
            for (int m = 0; m < 5; m++) {
                msf_flags_t fl = 0; uint64_t got = e->f(a, b, m, &fl);
                if (b_isnan(fa, a) || b_isnan(fb, b)) { int w[2] = {e->a, e->b}; uint64_t v[2] = {a, b}; nan_check(e->n, e->d, 2, w, v, got, fl, 0); continue; }
                Res R = ref_arith(e->op, e->d, e->a, e->b, a, b, m);
                if (R.skip) { g_skipped++; continue; }
                g_checked++;
                if (got != R.r || fl != R.fl) { char in[64]; snprintf(in, sizeof in, "%llx %llx", (unsigned long long)a, (unsigned long long)b); report(e->n, m, in, got, fl, R.r, R.fl, &printed); }
            }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}
static void test_uns(long n_each) {
    for (size_t i = 0; i < sizeof UNS / sizeof UNS[0]; i++) {
        const UnEnt *e = &UNS[i];
        const Fmt *fa = FMT(e->a);
        int printed = 0; long mism0 = g_mism;
        long n = (e->a == 16) ? 65536 : n_each;
        for (long k = 0; k < n; k++) {
            uint64_t a = (e->a == 16) ? (uint64_t)k : gen_val(fa);
            for (int m = 0; m < 5; m++) {
                msf_flags_t fl = 0; uint64_t got = e->f(a, m, &fl);
                if (b_isnan(fa, a)) {
                    if (e->op == OP_CONV && e->d == e->a) { /* convertFormat same format: quiets sNaN with invalid */ }
                    int w[1] = {e->a}; uint64_t v[1] = {a}; nan_check(e->n, e->d, 1, w, v, got, fl, 0); continue;
                }
                Res R = ref_arith(e->op, e->d, e->a, 0, a, 0, m);
                if (R.skip) { g_skipped++; continue; }
                g_checked++;
                if (got != R.r || fl != R.fl) { char in[64]; snprintf(in, sizeof in, "%llx", (unsigned long long)a); report(e->n, m, in, got, fl, R.r, R.fl, &printed); }
            }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}
static void test_fmas(long n_homog, long n_mixed) {
    for (size_t i = 0; i < sizeof FMAS / sizeof FMAS[0]; i++) {
        const FmaEnt *e = &FMAS[i];
        long n = (e->d == e->a && e->a == e->b && e->b == e->c) ? n_homog : n_mixed;
        const Fmt *fa = FMT(e->a), *fb = FMT(e->b), *fc = FMT(e->c);
        int printed = 0; long mism0 = g_mism;
        for (long k = 0; k < n; k++) {
            uint64_t a = gen_val(fa), b = gen_val(fb), c;
            int kind = rnd() % 4;
            if (kind == 0 && !b_isnan(fa, a) && !b_isnan(fb, b)) {
                /* addend near -(a*b): heavy cancellation */
                double p = b2d(e->a, a) * b2d(e->b, b);
                uint32_t fl; uint64_t cb = (e->c == 64) ? d2u(-p) : round_from_double(-p, e->c, 0, &fl);
                c = (cb + (rnd() % 5) - 2) & fc->all;
            } else c = gen_val(fc);
            if (rnd() % 16 == 0) { a = gen_nanish(fa); b = gen_nanish(fb); c = gen_nanish(fc); }
            for (int m = 0; m < 5; m++) {
                msf_flags_t fl = 0; uint64_t got = e->f(a, b, c, m, &fl);
                if (b_isnan(fa, a) || b_isnan(fb, b) || b_isnan(fc, c)) {
                    int zi = !b_isnan(fa, a) && !b_isnan(fb, b) && ((b_iszero(fa, a) && b_isinf(fb, b)) || (b_isinf(fa, a) && b_iszero(fb, b)));
                    int w[3] = {e->a, e->b, e->c}; uint64_t v[3] = {a, b, c}; nan_check(e->n, e->d, 3, w, v, got, fl, zi); continue;
                }
                Res R = ref_fma(e->d, e->a, e->b, e->c, a, b, c, m);
                if (R.skip) { g_skipped++; continue; }
                g_checked++;
                if (got != R.r || fl != R.fl) { char in[80]; snprintf(in, sizeof in, "%llx %llx %llx", (unsigned long long)a, (unsigned long long)b, (unsigned long long)c); report(e->n, m, in, got, fl, R.r, R.fl, &printed); }
            }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}

/* ---- integer conversions ---- */
static void int_range(int sgn, int bits, double *lo, double *hi_excl) {
    if (sgn) { *lo = -ldexp(1.0, bits - 1); *hi_excl = ldexp(1.0, bits - 1); } else { *lo = 0; *hi_excl = ldexp(1.0, bits); }
}
static double round_int_mode(double x, int mode, uint32_t *fl) { /* x finite: exact integral value in mode */
    double r;
    hw_begin(0);
    switch (mode) { case 0: r = hround_8(x); break; case 1: r = hround_11(x); break; case 2: r = hround_10(x); break; case 3: r = hround_9(x); break;
    default: { double t = hround_11(x); double fr = x - t; r = (fabs(fr) >= 0.5) ? t + copysign(1.0, x) : t; } }
    *fl = hw_end();
    return r;
}
static void test_tos(long n_each) {
    for (size_t i = 0; i < sizeof TOS / sizeof TOS[0]; i++) {
        const ToEnt *e = &TOS[i];
        const Fmt *fs = FMT(e->s);
        int printed = 0; long mism0 = g_mism;
        long n = (e->s == 16) ? 65536 : n_each;
        double lo, hi; int_range(e->sgn, e->bits, &lo, &hi);
        for (long k = 0; k < n; k++) {
            uint64_t a;
            if (e->s == 16) a = (uint64_t)k;
            else if (rnd() % 3 == 0) {
                /* values near the integer range edges and near half-integers */
                double base = (rnd() & 1) ? lo : hi; double v = base + (double)((int64_t)(rnd() % 7) - 3) * 0.5 + ((rnd() & 1) ? 0.25 : 0);
                if (e->s == 64) a = d2u(v); else { uint32_t fl; a = round_from_double(v, e->s, (int)(rnd() % 4), &fl); }
            } else a = gen_val(fs);
            msf_flags_t fl = 0; uint64_t got = e->f(a, &fl);
            uint64_t mask = e->bits == 64 ? ~0ull : ((1ull << e->bits) - 1);
            got &= mask;
            uint64_t exp; uint32_t efl = 0;
            uint64_t smax = e->sgn ? ((1ull << (e->bits - 1)) - 1) : mask;
            uint64_t smin = e->sgn ? (1ull << (e->bits - 1)) : 0;   /* two's complement min, masked */
            if (b_isnan(fs, a)) { exp = 0; efl = MSF_FLAG_INVALID; }
            else {
                double x = b2d(e->s, a);
                if (isinf(x)) { efl = MSF_FLAG_INVALID; exp = x > 0 ? smax : smin; }
                else {
                    uint32_t rfl; double r = round_int_mode(x, e->mode, &rfl);
                    if (r < lo || r >= hi) { efl = MSF_FLAG_INVALID; exp = r >= hi ? smax : smin; }
                    else {
                        if (e->sgn) exp = (uint64_t)(int64_t)r; else exp = (r >= 0x1p63) ? ((uint64_t)(r - 0x1p63) | (1ull << 63)) : (uint64_t)(int64_t)r;
                        if (e->exact && r != x) efl = MSF_FLAG_INEXACT;
                    }
                }
            }
            exp &= mask;
            g_checked++;
            if (got != exp || fl != efl) { char in[40]; snprintf(in, sizeof in, "%llx", (unsigned long long)a); report(e->n, e->mode, in, got, fl, exp, efl, &printed); }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}
static void test_froms(long n_each) {
    for (size_t i = 0; i < sizeof FROMS / sizeof FROMS[0]; i++) {
        const FromEnt *e = &FROMS[i];
        int printed = 0; long mism0 = g_mism;
        for (long k = 0; k < n_each; k++) {
            uint64_t raw = rnd();
            int sh = (int)(rnd() % 64); if (rnd() & 1) raw >>= sh;
            if (rnd() % 4 == 0) raw = (raw & ~((1ull << (rnd() % 40)) - 1)) | (1ull << (rnd() % 12)); /* tie-ish patterns */
            uint64_t mask = e->bits == 64 ? ~0ull : ((1ull << e->bits) - 1);
            uint64_t a = raw & mask;
            int64_t sv = 0;
            if (e->sgn) { sv = (e->bits == 64) ? (int64_t)a : ((int64_t)(a << (64 - e->bits)) >> (64 - e->bits)); }
            for (int m = 0; m < 5; m++) {
                msf_flags_t fl = 0; uint64_t got = e->f(e->sgn ? (uint64_t)sv : a, m, &fl);
                Res R = {0, 0, 0};
                if (e->d == 64) {
                    if (m < 4) { hw_begin(m); double r = e->sgn ? hcvt_i64(sv) : hcvt_u64(a); R.fl = hw_end(); R.r = d2u(r); }
                    else { /* ties-away by integer tie detection */
                        uint64_t mag = e->sgn ? (sv < 0 ? (uint64_t)0 - (uint64_t)sv : (uint64_t)sv) : a;
                        int top = mag ? 63 - __builtin_clzll(mag) : 0; int tie = 0;
                        if (top >= 53) { int drop = top - 52; uint64_t rem = mag & ((1ull << drop) - 1); tie = (rem == (1ull << (drop - 1))); }
                        int mm = tie ? ((e->sgn && sv < 0) ? 3 : 2) : 0;
                        hw_begin(mm); double r = e->sgn ? hcvt_i64(sv) : hcvt_u64(a); R.fl = hw_end(); R.r = d2u(r);
                    }
                } else {
                    hw_begin(1); double r = e->sgn ? hcvt_i64(sv) : hcvt_u64(a); uint32_t f1 = hw_end();
                    R.r = round_from_double(odd(r, f1), e->d, m, &R.fl);
                }
                g_checked++;
                if (got != R.r || fl != R.fl) { char in[40]; snprintf(in, sizeof in, "%lld/%llu", (long long)sv, (unsigned long long)a); report(e->n, m, in, got, fl, R.r, R.fl, &printed); }
            }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}
static void test_rtis(long n_each) {
    for (size_t i = 0; i < sizeof RTIS / sizeof RTIS[0]; i++) {
        const RtiEnt *e = &RTIS[i];
        const Fmt *fd = FMT(e->d);
        int printed = 0; long mism0 = g_mism;
        long n = (e->d == 16) ? 65536 : n_each;
        for (long k = 0; k < n; k++) {
            uint64_t a = (e->d == 16) ? (uint64_t)k : gen_val(fd);
            for (int m = 0; m < (e->exact ? 5 : 1); m++) {
                int mode = e->exact ? m : e->mode;
                msf_flags_t fl = 0; uint64_t got = e->f(a, m, &fl);
                if (b_isnan(fd, a)) { int w[1] = {e->d}; uint64_t v[1] = {a}; nan_check(e->n, e->d, 1, w, v, got, fl, 0); continue; }
                double x = b2d(e->d, a); uint32_t rfl; double r = isinf(x) ? x : round_int_mode(x, mode, &rfl);
                uint32_t efl = (e->exact && r != x) ? MSF_FLAG_INEXACT : 0;
                uint32_t dummy; uint64_t exp = (e->d == 64) ? d2u(r) : round_from_double(r, e->d, 0, &dummy);
                g_checked++;
                if (got != exp || fl != efl) { char in[40]; snprintf(in, sizeof in, "%llx", (unsigned long long)a); report(e->n, mode, in, got, fl, exp, efl, &printed); }
            }
        }
        if (g_mism != mism0) printf("%s: %ld mismatches\n", e->n, g_mism - mism0);
    }
}

int main(int argc, char **argv) {
    long scale = argc > 1 ? atol(argv[1]) : 1;
    seed(argc > 2 ? strtoull(argv[2], 0, 0) : 12345);
    test_bins(40000 * scale, 4000 * scale);
    printf("[bins] checked=%ld mism=%ld skipped=%ld\n", g_checked, g_mism, g_skipped); fflush(stdout);
    test_uns(40000 * scale);
    printf("[uns] checked=%ld mism=%ld skipped=%ld\n", g_checked, g_mism, g_skipped); fflush(stdout);
    test_fmas(40000 * scale, 1500 * scale);
    printf("[fma] checked=%ld mism=%ld skipped=%ld\n", g_checked, g_mism, g_skipped); fflush(stdout);
    test_tos(6000 * scale);
    printf("[toint] checked=%ld mism=%ld\n", g_checked, g_mism); fflush(stdout);
    test_froms(6000 * scale);
    printf("[fromint] checked=%ld mism=%ld\n", g_checked, g_mism); fflush(stdout);
    test_rtis(40000 * scale);
    printf("[rti] checked=%ld mism=%ld\n", g_checked, g_mism); fflush(stdout);
    printf("NaN-operand cases: %ld  flag-mismatch=%ld  result-not-NaN=%ld  payload: first-NaN-rule=%ld sNaN-first-rule=%ld neither=%ld\n",
           nan_cases, nan_flag_bad, nan_notnan, nan_h1, nan_h2, nan_other);
    printf("TOTAL checked=%ld mismatches=%ld skipped(ta-unknown)=%ld\n", g_checked, g_mism, g_skipped);
    return g_mism != 0;
}
