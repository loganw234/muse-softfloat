"""make_ias15_extract.py - regenerate the IAS15 workload extract.

Produces, in the output directory (demo/cache/ias15-extract via
run_demo.sh), exactly the file set the board build consumes
(board/CMakeLists.txt, IAS15_EXTRACT_DIR):

  integrator_ias15_min.c   IAS15 step core, extracted from the
                           fetched REBOUND 5.2.2 sources
  gravity_basic_min.c      BASIC gravity, same extraction
  sim_min.c                minimal simulation wrapper (template
                           below, project-authored for this extract)
  ias15x.c                 board/ias15_api.h implementation over
                           the extract (template below)
  reb_min.h                the extract's declarations (template)

The two extracted files are GPL-3.0-or-later REBOUND derivatives:
they are generated into the gitignored demo cache at run time and
must never be committed.  Extraction is by pinned line ranges plus
anchored text transforms over the fetched 5.2.2 tree; every
transform asserts its hit count, so upstream drift fails loudly
instead of producing a silent mis-extract.  Keep/deletion list
(SF-0 Sec.9 extraction pins): IAS15 step core with all adaptive
modes, BASIC gravity only (the executed branch verbatim),
variational/map/MEGNO/velocity-predict code deleted, allocation
replaced by one caller-owned arena with upstream zeroing
semantics, warning/error sinks as counters.  Coefficient tables
are carried as binary64 bit patterns taken from the committed
board/ias15_tables.h (mpmath-verified correctly rounded
conversions of the upstream literals), so no decimal literal is
ever re-converted here.

Usage: make_ias15_extract.py <rebound-tree-dir> <out-dir>
           [--tables-header PATH]
The tables header defaults to board/ias15_tables.h beside this
script's repository root.
Exit status: 0 = extract written; 1 = failure; 2 = usage.
"""
import hashlib
import pathlib
import re
import sys


def read_lines(path):
    return path.read_bytes().decode("utf-8").splitlines(keepends=True)


def take(lines, a, b):
    """1-based inclusive line range."""
    return "".join(lines[a - 1:b])


def replace(text, old, new, want, label):
    got = text.count(old)
    if got != want:
        raise SystemExit("make_ias15_extract: FAIL - %s: expected %d "
                         "hits, got %d (source drift)" % (label, want, got))
    return text.replace(old, new)


def drop_range(text, first, last, label, extra_after=0):
    """Drop lines from the one starting with `first` through the
    first later line whose stripped content equals `last`, plus
    extra_after further lines."""
    lines = text.splitlines(keepends=True)
    i = next((k for k, ln in enumerate(lines)
              if ln.lstrip().startswith(first)), None)
    if i is None:
        raise SystemExit("make_ias15_extract: FAIL - %s: start not "
                         "found: %r" % (label, first))
    j = next((k for k in range(i, len(lines))
              if lines[k].strip() == last), None)
    if j is None:
        raise SystemExit("make_ias15_extract: FAIL - %s: end not "
                         "found: %r" % (label, last))
    del lines[i:j + 1 + extra_after]
    return "".join(lines)


def table_block(tables_header):
    """Emit the coefficient tables as binary64 bit-pattern unions,
    parsing the committed board/ias15_tables.h data."""
    text = tables_header.read_bytes().decode("utf-8")
    out = ["/* Tables carried as binary64 bit patterns (SF-0 Sec.9): values are",
           " * the mpmath-verified correctly rounded conversions of the upstream",
           " * decimal literals, as committed in board/ias15_tables.h;",
           " * generated by demo/make_ias15_extract.py, do not edit by hand. The",
           " * upstream array names h/rr/c/d alias these bits as doubles. */",
           "typedef union { uint64_t u; double d; } reb_min_dbits_t;"]
    for name, want in (("h", 8), ("rr", 28), ("c", 21), ("d", 21)):
        m = re.search(r"ias15_table_%s_bits\[%d\]\s*=\s*\{([^}]*)\}"
                      % (name, want), text)
        if not m:
            raise SystemExit("make_ias15_extract: FAIL - table %s not "
                             "found in %s" % (name, tables_header))
        bits = re.findall(r"0x[0-9a-fA-F]{16}", m.group(1))
        if len(bits) != want:
            raise SystemExit("make_ias15_extract: FAIL - table %s has "
                             "%d entries in %s, want %d"
                             % (name, len(bits), tables_header, want))
        vals = ", ".join("{%sULL}" % b.lower() for b in bits)
        out.append("static const reb_min_dbits_t reb_min_%s_u[%d] = {%s};"
                   % (name, want, vals))
        out.append("static const double *const %s = &reb_min_%s_u[0].d;"
                   % (name, name))
    return "\n".join(out) + "\n"


NOTE = ("/* Generated into the demo cache by demo/make_ias15_extract.py\n"
        " * from the pinned REBOUND 5.2.2 archive (docs/metrics/fetches.jsonl).\n"
        " * GPL-3.0-or-later derivative: never commit this file. */\n")


def build_integrator(src_dir, tables_header):
    lines = read_lines(src_dir / "integrator_ias15.c")
    parts = []
    parts.append(take(lines, 1, 35))            # licence header
    parts.append(NOTE)
    parts.append('#include "reb_min.h"\n#include <string.h>\n#include <math.h>\n')
    parts.append(take(lines, 153, 176))         # dp7 structs + helper decls
    parts.append(take(lines, 179, 182))         # constants banner + safety_factor
    parts.append(table_block(tables_header))
    parts.append(take(lines, 195, 228))         # sqrt7 + dpcast
    # realloc_dp7 replaced by an arena zero (buffers pre-carved by sim_min).
    parts.append(
        "static void zero_dp7(double* REB_RESTRICT p, const size_t N3){\n"
        "    for (size_t i=0;i<N3*7;i++){\n"
        "        p[i] = 0.0;\n"
        "    }\n"
        "}\n")
    parts.append(take(lines, 237, 242))         # add_cs
    # Arena alloc: upstream zeroing semantics, no realloc (sim_min carves).
    parts.append(
        "static void reb_integrator_ias15_alloc(struct reb_simulation* r, struct reb_integrator_ias15_state* ias15){\n"
        "    const size_t N3 = 3*(r->N);\n"
        "    if (N3 > ias15->N_allocated) {\n"
        "        zero_dp7(ias15->g, N3);\n"
        "        zero_dp7(ias15->e, N3);\n"
        "        zero_dp7(ias15->b, N3);\n"
        "        zero_dp7(ias15->csb, N3);\n"
        "        zero_dp7(ias15->er, N3);\n"
        "        zero_dp7(ias15->br, N3);\n"
        "        double* REB_RESTRICT const csx = ias15->csx;\n"
        "        double* REB_RESTRICT const csv = ias15->csv;\n"
        "        for (size_t i=0;i<N3;i++){\n"
        "            // Kill compensated summation coefficients\n"
        "            csx[i] = 0;\n"
        "            csv[i] = 0;\n"
        "        }\n"
        "        ias15->N_allocated = N3;\n"
        "    }\n"
        "}\n")
    body = take(lines, 277, 883)                # step_try .. step
    # --- header of step_try: drop particles_var/map/N_var selection ---
    body = replace(body,
        "    struct reb_particle* const particles = r->particles;\n"
        "    struct reb_particle* const particles_var = r->particles_var;\n"
        "    size_t N;             // Number of real particles\n"
        "    size_t N_var;         // Number of variational particles\n"
        "    size_t* map = r->map; // this map allow for integrating only a selection of particles \n"
        "    if (map){\n"
        "        N = r->N_map;\n"
        "        N_var = 0;\n"
        "    }else{\n"
        "        N = r->N;\n"
        "        N_var = r->N_var;\n"
        "    }\n"
        "    const size_t N3 = 3*(N+N_var);\n",
        "    struct reb_particle* const particles = r->particles;\n"
        "    const size_t N = r->N; // extract: map/variational deleted\n"
        "    const size_t N3 = 3*N;\n",
        1, "step_try header")
    # --- delete variational copy loop (x0 fill) ---
    body = drop_range(body, "for(size_t mk=0;mk<N_var;mk++) {",
                      "a0[3*k+2] = particles_var[mk].az;", "var x0 loop",
                      extra_after=1)
    # --- COMPENSATED csa0: keep executed else branch only ---
    body = replace(body,
        "    if (r->gravity==REB_GRAVITY_COMPENSATED){\n"
        "        for(size_t k=0;k<N+N_var;k++) {\n"
        "            size_t mk = map ? map[k] : k;\n"
        "            csa0[3*k]   = gravity_cs[mk].x;\n"
        "            csa0[3*k+1] = gravity_cs[mk].y;  \n"
        "            csa0[3*k+2] = gravity_cs[mk].z;\n"
        "        }\n"
        "    }else{\n"
        "        gravity_cs = (struct reb_vec3d*)csa0; // Always 0.\n"
        "        for(size_t k=0;k<N3;k++) {\n"
        "            csa0[k]   = 0;\n"
        "        }\n"
        "    }\n",
        "    /* extract: BASIC gravity only (upstream else branch, verbatim) */\n"
        "    gravity_cs = (struct reb_vec3d*)csa0; // Always 0.\n"
        "    for(size_t k=0;k<N3;k++) {\n"
        "        csa0[k]   = 0;\n"
        "    }\n",
        1, "compensated branch")
    # --- MEGNO deletions ---
    body = replace(body,
        "    double integrator_megno_thisdt = 0.;\n"
        "    double integrator_megno_thisdt_init = 0.;\n"
        "    if (r->calculate_megno){\n"
        "        integrator_megno_thisdt_init = w[0]* (r->t-r->megno_initial_t) * reb_tools_megno_deltad_delta(r);\n"
        "    }\n",
        "", 1, "megno init")
    body = replace(body, "        integrator_megno_thisdt = integrator_megno_thisdt_init;\n",
                   "", 1, "megno copy")
    body = replace(body,
        "            if (r->calculate_megno){\n"
        "                integrator_megno_thisdt += w[n] * (r->t-r->megno_initial_t) * reb_tools_megno_deltad_delta(r);\n"
        "            }\n",
        "", 1, "megno stage")
    body = replace(body,
        "    if (r->calculate_megno){\n"
        "        double dY = dt_done*integrator_megno_thisdt;\n"
        "        reb_tools_megno_update(r, dY, dt_done);\n"
        "    }\n",
        "", 1, "megno update")
    # --- velocity-predict branch (false in pinned config) ---
    # End anchor is the var-branch last velocity line; then 3 closing
    # brace lines follow (else-close, for-close, if-close).
    body = drop_range(body,
        "if (r->calculate_megno || (r->additional_forces && r->force_is_velocity_dependent)){",
        "particles_var[mi].vz = vk2 + v0[k2];", "velocity predict",
        extra_after=3)
    # --- position-predict var else-branch ---
    body = replace(body,
        "                if (i<N){\n"
        "                    size_t mi = map ? map[i] : i;\n"
        "                    particles[mi].x = xk0 + x0[k0];\n"
        "                    particles[mi].y = xk1 + x0[k1];\n"
        "                    particles[mi].z = xk2 + x0[k2];\n"
        "                }else{\n"
        "                    size_t mi = i-N;\n"
        "                    particles_var[mi].x = xk0 + x0[k0];\n"
        "                    particles_var[mi].y = xk1 + x0[k1];\n"
        "                    particles_var[mi].z = xk2 + x0[k2];\n"
        "                }\n",
        "                particles[i].x = xk0 + x0[k0];\n"
        "                particles[i].y = xk1 + x0[k1];\n"
        "                particles[i].z = xk2 + x0[k2];\n",
        1, "position var branch")
    # --- remaining variational loops (at fill, reject reset, final swap) ---
    body = drop_range(body, "for(size_t mk=0;mk<N_var;++mk) {",
                      "at[3*k+2] = particles_var[mk].az;", "var at loop",
                      extra_after=1)
    body = drop_range(body, "for(size_t mk=0;mk<N_var;++mk) {",
                      "particles_var[mk].az = a0[3*k+2];", "var reset loop",
                      extra_after=1)
    body = drop_range(body, "for(size_t mk=0;mk<N_var;++mk) {",
                      "particles_var[mk].vz = v0[3*k+2];", "var swap loop",
                      extra_after=1)
    # --- generic leftovers ---
    n_map = body.count("map ? map[k] : k") + body.count("map ? map[i] : i")
    body = body.replace("map ? map[k] : k", "k").replace("map ? map[i] : i", "i")
    print("integrator: map ternaries neutralised: %d" % n_map)
    n_nvar = body.count("N+N_var")
    body = body.replace("N+N_var", "N")
    print("integrator: N+N_var folded: %d" % n_nvar)
    for bad in ("particles_var", "calculate_megno", "integrator_megno",
                "additional_forces", "particle_var", "->map"):
        if bad in body:
            raise SystemExit("make_ias15_extract: FAIL - leftover in "
                             "integrator extract: %s" % bad)
    parts.append(body)
    parts.append(
        "\nuint64_t reb_min_table_bits(int which, size_t i){\n"
        "    switch (which){\n"
        "    case 0: return i < 8 ? reb_min_h_u[i].u : 0;\n"
        "    case 1: return i < 28 ? reb_min_rr_u[i].u : 0;\n"
        "    case 2: return i < 21 ? reb_min_c_u[i].u : 0;\n"
        "    case 3: return i < 21 ? reb_min_d_u[i].u : 0;\n"
        "    default: return 0;\n"
        "    }\n"
        "}\n"
        "size_t reb_min_table_len(int which){\n"
        "    switch (which){ case 0: return 8; case 1: return 28;\n"
        "                    case 2: return 21; case 3: return 21;\n"
        "                    default: return 0; }\n"
        "}\n")
    return "".join(parts)


def build_gravity(src_dir):
    lines = read_lines(src_dir / "gravity.c")
    parts = [take(lines, 1, 31), NOTE,
             '#include "reb_min.h"\n#include <math.h>\n',
             take(lines, 39, 39),
             take(lines, 167, 282)]
    return "".join(parts)


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    tables_header = None
    i = 1
    while i < len(argv):
        if argv[i] == "--tables-header" and i + 1 < len(argv):
            tables_header = pathlib.Path(argv[i + 1])
            i += 1
        i += 1
    if len(args) != 2:
        print("usage: make_ias15_extract.py <rebound-tree-dir> <out-dir> "
              "[--tables-header PATH]")
        return 2
    tree = pathlib.Path(args[0])
    out_dir = pathlib.Path(args[1])
    src_dir = tree / "src"
    version_file = tree / "version.txt"
    if not version_file.is_file():
        print("make_ias15_extract: FAIL - no version.txt under %s "
              "(pass the fetched REBOUND tree)" % tree)
        return 1
    version = version_file.read_bytes().decode("utf-8").strip()
    if version != "5.2.2":
        print("make_ias15_extract: FAIL - REBOUND version.txt says %r, "
              "the pinned extract is for 5.2.2 - refusing" % version)
        return 1
    for name in ("integrator_ias15.c", "gravity.c"):
        if not (src_dir / name).is_file():
            print("make_ias15_extract: FAIL - no src/%s under %s"
                  % (name, tree))
            return 1
    if tables_header is None:
        tables_header = (pathlib.Path(__file__).resolve().parents[1]
                         / "board" / "ias15_tables.h")
    if not tables_header.is_file():
        print("make_ias15_extract: FAIL - tables header not found: %s"
              % tables_header)
        return 1
    outs = {
        "integrator_ias15_min.c": build_integrator(src_dir, tables_header),
        "gravity_basic_min.c": build_gravity(src_dir),
        "reb_min.h": REB_MIN_H,
        "sim_min.c": SIM_MIN_C,
        "ias15x.c": IAS15X_C,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in outs.items():
        (out_dir / name).write_bytes(text.encode("utf-8"))
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        print("extract/%s: %d lines sha256 %s"
              % (name, text.count("\n"), digest))
    print("IAS15-EXTRACT OK")
    return 0


